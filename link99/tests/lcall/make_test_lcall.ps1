# make_test_lcall.ps1 -- build LTEST.COM, the test of LCALL (32-bit arithmetic),
# and MERSENNE.COM, the Lucas-Lehmer prime test that uses it.
#
# Compiles LTEST.C and MERSENNE.C, assembles them (with MPLL.A99, and the
# demo's STARTUP and CONOUT from ..\ovly), links each with CALL.R99 and
# LCALL.R99 from link99\lib, and copies both to the SBC MONITOR folder if one
# is found ($env:SBC_MONITOR_DIR, or a TMS99105_SBC\MONITOR folder above).
#
# On the SBC:
#   LTEST           ->  LTEST: 1504 passed, 0 failed
#   MERSENNE        ->  2^p-1 prime or composite for a list of small p
#   MERSENNE 1279   ->  tests 2^1279-1 and prints its 386 digits
#
# LTEST.C is generated by gen_ltest.py, which computes every expected value
# itself; rerun it (python gen_ltest.py) after changing the test vectors.
# LCALL.R99 is assembled from iolib99\src\lcall.A99 in the
# Relocating-Assembler-and-Linker-Loader-for-TMS99000 repository.
$ErrorActionPreference = "Stop"
$Here  = if($PSScriptRoot) { $PSScriptRoot } else { (Get-Location).Path }
$L99   = Split-Path -Parent (Split-Path -Parent $Here)
$Ovly  = Join-Path (Split-Path -Parent $Here) "ovly"
$Build = Join-Path $Here "build"
$MonitorDir = $env:SBC_MONITOR_DIR
if(-not $MonitorDir) {
    $up = Split-Path -Parent $L99
    while($up) {
        $c = Join-Path $up "TMS99105_SBC\MONITOR"
        if(Test-Path -LiteralPath $c -PathType Container) { $MonitorDir = $c; break }
        $next = Split-Path -Parent $up
        if(-not $next -or $next -eq $up) { break }
        $up = $next
    }
}
if(Test-Path -LiteralPath $Build) { Remove-Item -LiteralPath $Build -Recurse -Force }
New-Item -ItemType Directory -Path $Build | Out-Null
Copy-Item (Join-Path $L99 "tools\*.exe") $Build -Force
Copy-Item (Join-Path $L99 "lib\call.R99"), (Join-Path $L99 "lib\LCALL.R99") $Build -Force
Copy-Item (Join-Path $Ovly "STARTUP.A99"), (Join-Path $Ovly "CONOUT.A99") $Build -Force
Copy-Item (Join-Path $Here "LTEST.C"), (Join-Path $Here "MERSENNE.C"), (Join-Path $Here "MPLL.A99") $Build -Force
Push-Location $Build
[Environment]::CurrentDirectory = (Get-Location).Path
try {
    foreach($c in @("LTEST","MERSENNE")) {
        $o = & .\smallcp.exe -C $c 2>&1 | Out-String
        if($o -notmatch "Errors:\s+0") { Write-Output $o; throw "compile failed: $c" }
    }
    foreach($a in @("LTEST","MERSENNE","MPLL","STARTUP","CONOUT")) {
        $o = & .\r99.exe $a SCHC 2>&1 | Out-String
        if($o -notmatch "No error\(s\)") { Write-Output $o; throw "assemble failed: $a" }
    }
    $links = @(
        @("LTEST.COM","STARTUP.R99","LTEST.R99","CONOUT.R99","CALL.R99","LCALL.R99"),
        @("MERSENNE.COM","STARTUP.R99","MERSENNE.R99","MPLL.R99","CONOUT.R99","CALL.R99","LCALL.R99"))
    foreach($l in $links) {
        $o = & .\link99.exe -O1000 -S @l 2>&1 | Out-String
        if($o -match '(?im)^\s*-\s*Unresolved:|\*{3}\s*FATAL') { Write-Output $o; throw ("link failed: " + $l[0]) }
        $com = Get-Item (".\" + $l[0])
        Write-Output ("{0} {1} bytes" -f $l[0], $com.Length)
    }
    if($MonitorDir -and (Test-Path -LiteralPath $MonitorDir -PathType Container)) {
        Copy-Item ".\LTEST.COM", ".\MERSENNE.COM" $MonitorDir -Force
        Write-Output ("Copied LTEST.COM and MERSENNE.COM to " + $MonitorDir)
    } else {
        Write-Output ("No MONITOR folder found; LTEST.COM and MERSENNE.COM are in " + $Build)
    }
}
finally {
    Pop-Location
    [Environment]::CurrentDirectory = (Get-Location).Path
}
